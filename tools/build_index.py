#!/usr/bin/env python3
"""Generate (or verify) mcp-top-10-2025.json from the entry files themselves.

Run `python tools/build_index.py` to write the file, or with `--check` to
regenerate in memory and fail if the committed copy has drifted. CI runs the
second form, so renaming an entry breaks the build instead of leaving an index
that still reads as authoritative while no longer describing the list.

The output is deterministic: every field comes from the tree or from git, and
`source.commit` is the last commit that touched `2025/` rather than HEAD. That
matters — pinning to HEAD would change the file on every unrelated commit and
would never match inside a pull request, where HEAD is a merge commit that did
not exist when the file was written.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import urllib.parse
from pathlib import Path

REPO_URL = "https://github.com/OWASP/www-project-mcp-top-10"
SITE = "https://owasp.org/www-project-mcp-top-10/"
ENTRIES_DIR = "2025"
OUTPUT = "mcp-top-10-2025.json"
EXPECTED_ENTRIES = 10

ROOT = Path(__file__).resolve().parent.parent


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=True
    ).stdout.strip()


def entry_files() -> list[Path]:
    files = sorted((ROOT / ENTRIES_DIR).glob("MCP*.md"))
    if len(files) != EXPECTED_ENTRIES:
        raise SystemExit(
            f"expected {EXPECTED_ENTRIES} entry files in {ENTRIES_DIR}/, found {len(files)}. "
            "If the list genuinely changed size, update EXPECTED_ENTRIES deliberately."
        )
    return files


def read_entry(path: Path) -> dict:
    body = path.read_text(encoding="utf-8")

    title_match = re.search(r'^title:\s*"([^"]+)"', body, re.M)
    if not title_match:
        raise SystemExit(f"{path.name}: no title in front matter")
    published = title_match.group(1)

    slug = path.stem
    # "MCP01:2025 - Name" and "MCP04:2025 – Name" both occur, so match either
    # separator rather than assuming the one this entry happens to use.
    short = re.sub(r"^MCP\d\d:2025\s*[-–]\s*", "", published).strip()

    # Recorded, not interpreted: the H3 headings this entry actually has. The
    # ten do not share a structure — only Impact, Example Attack Scenarios and
    # References appear in all of them — so this says what is there without
    # asserting what a category covers, which is the project's call and not a
    # generator's.
    sections = [
        re.sub(r"\s+", " ", h).strip().rstrip(":")
        for h in re.findall(r"^###\s+(.+?)\s*$", body, re.M)
        if not h.strip().startswith("[")
    ]

    return {
        "id": slug[:5],
        "title": short,
        "titleAsPublished": published,
        "slug": slug,
        "file": f"{ENTRIES_DIR}/{path.name}",
        "url": SITE + ENTRIES_DIR + "/" + urllib.parse.quote(slug, safe="&"),
        "sections": sections,
    }


def build() -> dict:
    # The commit that last changed the entries, not HEAD — see the module
    # docstring. This is what makes the output stable.
    commit = git("log", "-1", "--format=%H", "--", ENTRIES_DIR)
    commit_date = git("log", "-1", "--format=%cI", "--", ENTRIES_DIR)

    return {
        "_comment": (
            f"Machine-readable index of the OWASP MCP Top 10 ({ENTRIES_DIR}). Generated by "
            "tools/build_index.py from the entry files; do not hand-edit. CI regenerates "
            "and fails on any difference."
        ),
        "list": "OWASP MCP Top 10",
        "year": ENTRIES_DIR,
        "status": "beta",
        "source": {
            "repository": REPO_URL,
            "commit": commit,
            "commitDate": commit_date,
            "tree": f"{REPO_URL}/tree/{commit}/{ENTRIES_DIR}",
        },
        "notes": [
            "Slugs are not derivable from titles. The separator after '2025' is a plain "
            "hyphen (U+002D) in MCP01 and an en dash (U+2013) in the other nine; four slugs "
            "contain a literal '&'; MCP10 runs 'ContextInjection' together. 'url' is already "
            "percent-encoded, 'slug' is the raw filename stem.",
            "Titles carry the same split: MCP01-MCP03 use a hyphen between the number and the "
            "name, MCP04-MCP10 use an en dash.",
            "'sections' lists the H3 headings each entry actually has, recorded rather than "
            "interpreted. The ten do not share a structure: only Impact, Example Attack "
            "Scenarios and References appear in all of them.",
        ],
        "entries": [read_entry(p) for p in entry_files()],
    }


def serialize(doc: dict) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed file differs from a fresh generation",
    )
    args = parser.parse_args()

    generated = serialize(build())
    target = ROOT / OUTPUT

    if not args.check:
        target.write_text(generated, encoding="utf-8")
        print(f"wrote {OUTPUT}")
        return 0

    if not target.exists():
        print(f"{OUTPUT} is missing. Run: python tools/build_index.py", file=sys.stderr)
        return 1

    current = target.read_text(encoding="utf-8")
    if current == generated:
        print(f"{OUTPUT} is up to date")
        return 0

    import difflib

    print(f"{OUTPUT} does not match the entry files:\n", file=sys.stderr)
    diff = difflib.unified_diff(
        current.splitlines(keepends=True),
        generated.splitlines(keepends=True),
        fromfile=f"{OUTPUT} (committed)",
        tofile=f"{OUTPUT} (regenerated)",
    )
    sys.stderr.writelines(diff)
    print("\nRun: python tools/build_index.py", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
